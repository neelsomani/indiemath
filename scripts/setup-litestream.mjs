#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import {
  chmod,
  chown,
  mkdir,
  readFile,
  rename,
  unlink,
  writeFile,
} from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const arguments_ = new Set(process.argv.slice(2));

if (arguments_.has("--help")) {
  console.log(`
Usage: sudo ./setup-litestream.sh

Reads configuration from the repository .env file and the current environment,
writes /etc/indiemath/litestream.env with mode 0600, installs the systemd unit,
and enables and starts R2 replication.

Set INDIEMATH_ENV_FILE=/path/to/file to use another environment file.
Current environment variables take precedence over values in that file.
`.trim());
  process.exit(0);
}
if (arguments_.size > 0) {
  fail(`Unknown option(s): ${[...arguments_].join(", ")}`);
}
if (typeof process.getuid !== "function" || process.getuid() !== 0) {
  fail("Run this bootstrap as root: sudo ./setup-litestream.sh");
}
if (process.platform !== "linux") {
  fail("Litestream service setup must run on the Linux deployment host.");
}

const databasePath = absolutePath(
  process.env.INDIEMATH_DB_PATH
    ?? process.env.INDIEMATH_DB
    ?? "/var/lib/indiemath/ledger.sqlite",
  "INDIEMATH_DB_PATH or INDIEMATH_DB",
);
const metadataRoot = absolutePath(
  process.env.INDIEMATH_LITESTREAM_META_ROOT
    ?? "/var/lib/indiemath/litestream",
  "INDIEMATH_LITESTREAM_META_ROOT",
);
const replicaBucket = bucketName(required("R2_REPLICA_BUCKET"));
const endpoint = r2Endpoint(required("R2_ENDPOINT"));
const accessKeyId = environmentFileValue(
  required("R2_ACCESS_KEY_ID"),
  "R2_ACCESS_KEY_ID",
);
const secretAccessKey = environmentFileValue(
  required("R2_SECRET_ACCESS_KEY"),
  "R2_SECRET_ACCESS_KEY",
);
const serviceUser = resolveServiceUser();
const serviceGroup = commandOutput("id", ["-gn", serviceUser]);
const litestreamBinary = resolveExecutable(
  process.env.LITESTREAM_BIN ?? "litestream",
);
const systemctlBinary = resolveExecutable("systemctl");

const databaseDirectory = path.dirname(databasePath);
safeManagedDirectory(databaseDirectory, "database directory");
safeManagedDirectory(metadataRoot, "Litestream metadata directory");
await installDirectory(databaseDirectory, serviceUser, serviceGroup);
await installDirectory(metadataRoot, serviceUser, serviceGroup);

const environmentDirectory = "/etc/indiemath";
const environmentPath = path.join(environmentDirectory, "litestream.env");
await mkdir(environmentDirectory, { recursive: true, mode: 0o755 });
const environmentBody = [
  "# Generated by setup-litestream.sh. Do not edit or commit.",
  `INDIEMATH_DB_PATH=${environmentFileValue(databasePath, "INDIEMATH_DB_PATH")}`,
  `INDIEMATH_LITESTREAM_META_ROOT=${
    environmentFileValue(metadataRoot, "INDIEMATH_LITESTREAM_META_ROOT")
  }`,
  "",
  `R2_REPLICA_BUCKET=${replicaBucket}`,
  `R2_ENDPOINT=${endpoint}`,
  `R2_ACCESS_KEY_ID=${accessKeyId}`,
  `R2_SECRET_ACCESS_KEY=${secretAccessKey}`,
  "",
].join("\n");
await atomicWrite(environmentPath, environmentBody, 0o600);

const sourceUnitPath = path.join(rootDir, "ops", "indiemath-litestream.service");
let unit = await readFile(sourceUnitPath, "utf8");
unit = replaceUnitDirective(unit, "User", serviceUser);
unit = replaceUnitDirective(unit, "Group", serviceGroup);
unit = replaceUnitDirective(unit, "WorkingDirectory", rootDir);
unit = replaceUnitDirective(
  unit,
  "ExecStart",
  path.join(rootDir, "scripts", "replicate-ledger.sh"),
);
unit = replaceUnitDirective(
  unit,
  "ReadWritePaths",
  `${databaseDirectory} ${metadataRoot}`,
);
unit = unit.replace(
  /^EnvironmentFile=.*$/m,
  `EnvironmentFile=${environmentPath}\nEnvironment=LITESTREAM_BIN=${litestreamBinary}`,
);
const installedUnitPath = "/etc/systemd/system/indiemath-litestream.service";
await atomicWrite(installedUnitPath, unit, 0o644);

execFileSync(systemctlBinary, ["daemon-reload"], { stdio: "inherit" });
execFileSync(
  systemctlBinary,
  ["enable", "--now", "indiemath-litestream.service"],
  { stdio: "inherit" },
);

console.log(`Configured private Litestream environment at ${environmentPath}.`);
console.log(`Enabled R2 replication for ${databasePath} as ${serviceUser}.`);

function required(name) {
  const value = process.env[name];
  if (typeof value !== "string" || !value.trim()) {
    fail(`Missing required configuration: ${name}.`);
  }
  return value.trim();
}

function absolutePath(value, label) {
  if (typeof value !== "string" || !path.isAbsolute(value)) {
    fail(`${label} must be an absolute path.`);
  }
  const normalized = path.normalize(value);
  if (normalized === "/") fail(`${label} cannot be the filesystem root.`);
  return environmentFileValue(normalized, label);
}

function bucketName(value) {
  if (
    value.length < 3
    || value.length > 63
    || !/^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?$/.test(value)
  ) {
    fail("R2_REPLICA_BUCKET must be 3–63 lowercase letters, numbers, or hyphens.");
  }
  return value;
}

function r2Endpoint(value) {
  let url;
  try {
    url = new URL(value);
  } catch {
    fail("R2_ENDPOINT must be a valid HTTPS URL.");
  }
  if (
    url.protocol !== "https:"
    || !url.hostname.endsWith(".r2.cloudflarestorage.com")
    || (url.pathname !== "/" && url.pathname !== "")
    || url.search
    || url.hash
  ) {
    fail(
      "R2_ENDPOINT must be the account endpoint without a bucket path, query, or fragment.",
    );
  }
  return url.origin;
}

function environmentFileValue(value, label) {
  if (/[\r\n\0\s"'\\]/.test(value)) {
    fail(`${label} contains characters unsupported by the generated environment file.`);
  }
  return value;
}

function safeManagedDirectory(directory, label) {
  const segments = path.resolve(directory).split(path.sep).filter(Boolean);
  if (segments.length < 3) {
    fail(`${label} is too broad for setup to manage safely: ${directory}.`);
  }
}

function resolveServiceUser() {
  const proposed = process.env.INDIEMATH_SERVICE_USER
    ?? (process.env.SUDO_USER && process.env.SUDO_USER !== "root"
      ? process.env.SUDO_USER
      : "indiemath");
  if (!/^[a-z_][a-z0-9_-]*[$]?$/i.test(proposed)) {
    fail("INDIEMATH_SERVICE_USER is not a valid local user name.");
  }
  try {
    commandOutput("id", ["-u", proposed]);
  } catch {
    if (proposed !== "indiemath") {
      fail(`Deployment user does not exist: ${proposed}.`);
    }
    execFileSync("useradd", [
      "--system",
      "--home-dir",
      "/var/lib/indiemath",
      "--shell",
      "/usr/sbin/nologin",
      proposed,
    ], { stdio: "inherit" });
  }
  return proposed;
}

function resolveExecutable(name) {
  if (path.isAbsolute(name)) {
    try {
      execFileSync(name, ["version"], { stdio: "ignore" });
      return name;
    } catch {
      fail(`Executable is unavailable: ${name}.`);
    }
  }
  try {
    return commandOutput("which", [name]);
  } catch {
    fail(
      `${name} is not installed or not on PATH. Install it before running setup.`,
    );
  }
}

function commandOutput(command, args) {
  return execFileSync(command, args, {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
  }).trim();
}

async function installDirectory(directory, user, group) {
  execFileSync("install", [
    "-d",
    "-m",
    "0750",
    "-o",
    user,
    "-g",
    group,
    directory,
  ], { stdio: "inherit" });
}

async function atomicWrite(destination, body, mode) {
  const directory = path.dirname(destination);
  await mkdir(directory, { recursive: true });
  const temporary = path.join(
    directory,
    `.${path.basename(destination)}.${process.pid}.${Date.now()}.tmp`,
  );
  try {
    await writeFile(temporary, body, { encoding: "utf8", mode });
    await chmod(temporary, mode);
    await chown(temporary, 0, 0);
    await rename(temporary, destination);
  } finally {
    await unlink(temporary).catch(() => {});
  }
}

function replaceUnitDirective(unit, directive, value) {
  const pattern = new RegExp(`^${directive}=.*$`, "m");
  if (!pattern.test(unit)) fail(`Service template is missing ${directive}.`);
  return unit.replace(pattern, `${directive}=${value}`);
}

function fail(message) {
  console.error(message);
  process.exit(2);
}
